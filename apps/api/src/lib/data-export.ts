import type { PrismaClient } from '@tahti/db'

/** What the account itself made or did, beyond the profile and billing rows
 * the export always had: uploads, collections, posts, events, comments,
 * likes, reposts, follows, messages it sent, purchases, newsletter
 * subscriptions, the accounts it blocked, its listening sessions, the chat
 * messages it posted while signed in, its track reactions, and its feature
 * requests, motion comments, seconds and votes, its discussion replies and the discussion topics it follows (and whether it muted them) (the member already sees their
 * own choice on each motion), correction requests, its follow-ups on its
 * support requests, the radio stations, themes and embeds it added, what
 * it downloaded, the Tahti Jams it hosted or joined, the venues it runs and the venue shows it booked, any restrictions the board put on it (without who issued them), the tracks it sent to Tahti Radio and the radio stations it suggested, the fan subscription tiers and store items it offers, the notifications it received, its grants and fan-subscription payouts, the add-ons it published or installed, its signed-in devices and API tokens (names and prefixes, never the secrets), the private-track shares it made or received (never the link keys) the green rooms it was invited to, and its email address change requests (never the link tokens). Other
 * people appear by username only. */
export async function buildActivityExport(
  prisma: PrismaClient,
  user: { id: string; email: string; username: string },
) {
  const [
    sounds,
    collections,
    posts,
    events,
    comments,
    likes,
    reposts,
    following,
    collectionSubscriptions,
    messagesSent,
    purchases,
    newsletterSubscriptions,
    supportRequests,
    blockedAccounts,
    listening,
    chatMessages,
    trackReactions,
    featureRequests,
    featureRequestComments,
    featureRequestVotes,
    motionComments,
    motionSeconds,
    motionVotes,
    correctionRequests,
    supportReplies,
    radioStations,
    themes,
    embeds,
    downloads,
    jams,
    venues,
    venueShows,
    restrictions,
    radioSubmissions,
    stationSuggestions,
    fanTiers,
    storeItems,
    notifications,
    grants,
    fanSubscriptionPayouts,
    addonsPublished,
    addonInstalls,
    devices,
    apiTokens,
    sharesGiven,
    sharesReceived,
    greenRoomInvites,
    emailChanges,
    discussionPosts,
    discussionFollows,
  ] = await Promise.all([
    prisma.sound.findMany({
      where: { channel: { userId: user.id } },
      orderBy: { createdAt: 'asc' },
      select: {
        id: true,
        title: true,
        description: true,
        contentType: true,
        isPublic: true,
        status: true,
        createdAt: true,
      },
    }),
    prisma.collection.findMany({
      where: { userId: user.id },
      orderBy: { createdAt: 'asc' },
      select: { slug: true, name: true, visibility: true, createdAt: true },
    }),
    prisma.artistPost.findMany({
      where: { userId: user.id },
      orderBy: { createdAt: 'asc' },
      select: { title: true, body: true, linkUrl: true, publishAt: true, createdAt: true },
    }),
    prisma.artistEvent.findMany({
      where: { userId: user.id },
      orderBy: { startAt: 'asc' },
      select: { title: true, description: true, place: true, location: true, startAt: true },
    }),
    prisma.comment.findMany({
      where: { authorId: user.id },
      orderBy: { createdAt: 'asc' },
      select: {
        body: true,
        createdAt: true,
        sound: { select: { id: true, title: true } },
        channel: { select: { slug: true } },
      },
    }),
    prisma.soundLike.findMany({
      where: { userId: user.id },
      orderBy: { createdAt: 'asc' },
      select: { createdAt: true, sound: { select: { id: true, title: true } } },
    }),
    prisma.soundRepost.findMany({
      where: { userId: user.id },
      orderBy: { createdAt: 'asc' },
      select: { createdAt: true, sound: { select: { id: true, title: true } } },
    }),
    prisma.artistFollow.findMany({
      where: { followerUserId: user.id },
      orderBy: { createdAt: 'asc' },
      select: { createdAt: true, artist: { select: { username: true } } },
    }),
    prisma.collectionSubscription.findMany({
      where: { userId: user.id },
      orderBy: { createdAt: 'asc' },
      select: { createdAt: true, collection: { select: { slug: true, name: true } } },
    }),
    prisma.message.findMany({
      where: { senderId: user.id },
      orderBy: { createdAt: 'asc' },
      select: { body: true, createdAt: true, conversationId: true },
    }),
    prisma.purchase.findMany({
      where: { buyerUserId: user.id },
      orderBy: { createdAt: 'asc' },
      select: {
        amountCents: true,
        state: true,
        createdAt: true,
        tier: { select: { name: true } },
      },
    }),
    prisma.newsletterSubscriber.findMany({
      where: { email: user.email },
      select: {
        confirmedAt: true,
        unsubscribedAt: true,
        artist: { select: { username: true } },
      },
    }),
    prisma.supportTicket.findMany({
      where: { artistId: user.id },
      orderBy: { createdAt: 'asc' },
      select: { subject: true, message: true, category: true, status: true, createdAt: true },
    }),
    prisma.userBlock.findMany({
      where: { blockerUserId: user.id },
      orderBy: { createdAt: 'asc' },
      select: { createdAt: true, blocked: { select: { username: true } } },
    }),
    prisma.listenSession.findMany({
      where: { byUserId: user.id },
      orderBy: { startedAt: 'asc' },
      select: {
        channelId: true,
        soundId: true,
        source: true,
        startedAt: true,
        lastSeenAt: true,
        endedAt: true,
        countryCode: true,
        city: true,
        uaBrowser: true,
        uaOs: true,
        uaDeviceType: true,
        uaDeviceVendor: true,
        referrerHost: true,
        maxPositionSec: true,
        durationSec: true,
      },
    }),
    prisma.chatMessage.findMany({
      where: { userId: user.id },
      orderBy: { createdAt: 'asc' },
      select: {
        text: true,
        handle: true,
        fanOnly: true,
        createdAt: true,
        removedAt: true,
        channel: { select: { slug: true } },
      },
    }),
    prisma.trackReaction.findMany({
      where: { userId: user.id },
      orderBy: { createdAt: 'asc' },
      select: {
        type: true,
        positionSec: true,
        createdAt: true,
        sound: { select: { id: true, title: true } },
      },
    }),
    prisma.featureRequest.findMany({
      where: { proposedById: user.id },
      orderBy: { createdAt: 'asc' },
      select: { title: true, description: true, status: true, createdAt: true },
    }),
    prisma.featureRequestComment.findMany({
      where: { authorId: user.id },
      orderBy: { createdAt: 'asc' },
      select: { body: true, createdAt: true, featureRequest: { select: { title: true } } },
    }),
    prisma.featureRequestVote.findMany({
      where: { userId: user.id },
      orderBy: { createdAt: 'asc' },
      select: { createdAt: true, featureRequest: { select: { title: true } } },
    }),
    prisma.motionComment.findMany({
      where: { authorId: user.id },
      orderBy: { createdAt: 'asc' },
      select: {
        body: true,
        createdAt: true,
        removedAt: true,
        motion: { select: { id: true, title: true } },
      },
    }),
    prisma.motionSecond.findMany({
      where: { userId: user.id },
      orderBy: { createdAt: 'asc' },
      select: { createdAt: true, motion: { select: { id: true, title: true } } },
    }),
    prisma.vote.findMany({
      where: { userId: user.id },
      orderBy: { castAt: 'asc' },
      select: { choice: true, castAt: true, motion: { select: { id: true, title: true } } },
    }),
    prisma.governanceCorrectionRequest.findMany({
      where: { requesterId: user.id },
      orderBy: { createdAt: 'asc' },
      select: {
        subject: true,
        details: true,
        recordKind: true,
        state: true,
        resolutionNote: true,
        resolvedAt: true,
        createdAt: true,
      },
    }),
    prisma.supportTicketNote.findMany({
      where: { authorId: user.id, kind: 'MESSAGE', ticket: { artistId: user.id } },
      orderBy: { createdAt: 'asc' },
      select: { body: true, createdAt: true, ticket: { select: { subject: true } } },
    }),
    prisma.internetRadioStation.findMany({
      where: { userId: user.id },
      orderBy: { position: 'asc' },
      select: {
        name: true,
        genre: true,
        description: true,
        streamUrl: true,
        programmingUrl: true,
        iconUrl: true,
        createdAt: true,
      },
    }),
    prisma.theme.findMany({
      where: { userId: user.id },
      orderBy: { createdAt: 'asc' },
      select: {
        name: true,
        varsJson: true,
        darkJson: true,
        visibility: true,
        prUrl: true,
        createdAt: true,
      },
    }),
    prisma.artistEmbed.findMany({
      where: { userId: user.id },
      orderBy: { createdAt: 'asc' },
      select: { provider: true, url: true, title: true, createdAt: true },
    }),
    prisma.download.findMany({
      where: { byUserId: user.id },
      orderBy: { createdAt: 'asc' },
      select: {
        channelId: true,
        soundId: true,
        releaseTrackId: true,
        format: true,
        countryCode: true,
        createdAt: true,
      },
    }),
    prisma.jamParticipant.findMany({
      where: { userId: user.id },
      orderBy: { joinedAt: 'asc' },
      select: {
        role: true,
        joinedAt: true,
        leftAt: true,
        removedAt: true,
        session: {
          select: {
            code: true,
            createdAt: true,
            endedAt: true,
            host: { select: { username: true } },
          },
        },
      },
    }),
    prisma.venue.findMany({
      where: { createdBy: user.id },
      orderBy: { createdAt: 'asc' },
      select: {
        slug: true,
        name: true,
        address: true,
        city: true,
        countryCode: true,
        capacity: true,
        description: true,
        externalLinks: true,
        photos: true,
        verifiedAt: true,
        createdAt: true,
      },
    }),
    prisma.venueBroadcast.findMany({
      where: { artistUserId: user.id },
      orderBy: { startAt: 'asc' },
      select: {
        startAt: true,
        endAt: true,
        description: true,
        state: true,
        createdAt: true,
        venue: { select: { slug: true, name: true } },
      },
    }),
    prisma.accountRestriction.findMany({
      where: { userId: user.id },
      orderBy: { bannedAt: 'asc' },
      select: { type: true, reason: true, bannedAt: true, expiresAt: true, liftedAt: true },
    }),
    prisma.radioTrackSubmissionItem.findMany({
      where: { batch: { submitterId: user.id } },
      orderBy: { createdAt: 'asc' },
      select: {
        status: true,
        rejectionNote: true,
        reviewedAt: true,
        createdAt: true,
        sound: { select: { id: true, title: true } },
        batch: { select: { note: true } },
      },
    }),
    prisma.radioStationSuggestion.findMany({
      where: { submitterId: user.id },
      orderBy: { createdAt: 'asc' },
      select: {
        name: true,
        logoUrl: true,
        language: true,
        bitrateKbps: true,
        streamUrl: true,
        status: true,
        rejectionNote: true,
        reviewedAt: true,
        createdAt: true,
      },
    }),
    prisma.fanTier.findMany({
      where: { artistUserId: user.id },
      orderBy: { position: 'asc' },
      select: {
        name: true,
        amountCents: true,
        description: true,
        perks: true,
        active: true,
        createdAt: true,
      },
    }),
    prisma.purchaseTier.findMany({
      where: { artistUserId: user.id },
      orderBy: { position: 'asc' },
      select: {
        name: true,
        description: true,
        priceCents: true,
        priceOptional: true,
        active: true,
        createdAt: true,
        sounds: { select: { id: true, title: true } },
      },
    }),
    prisma.notification.findMany({
      where: { userId: user.id },
      orderBy: { createdAt: 'asc' },
      select: {
        type: true,
        title: true,
        body: true,
        url: true,
        readAt: true,
        createdAt: true,
        actor: { select: { username: true } },
      },
    }),
    prisma.grantDisbursement.findMany({
      where: { userId: user.id },
      orderBy: { forYear: 'asc' },
      select: {
        forYear: true,
        units: true,
        amountCents: true,
        state: true,
        notifiedAt: true,
        paidAt: true,
        publishedAs: true,
      },
    }),
    prisma.fanSubPayout.findMany({
      where: { artistUserId: user.id },
      orderBy: { forPeriodStart: 'asc' },
      select: {
        forPeriodStart: true,
        forPeriodEnd: true,
        grossCents: true,
        stripeFeeCents: true,
        orgFeeCents: true,
        netToArtistCents: true,
        state: true,
        paidAt: true,
      },
    }),
    prisma.addon.findMany({
      where: { authorUserId: user.id },
      orderBy: { createdAt: 'asc' },
      select: {
        slug: true,
        name: true,
        description: true,
        scope: true,
        currentVersion: true,
        status: true,
        moderationNote: true,
        createdAt: true,
      },
    }),
    prisma.addonInstall.findMany({
      where: { OR: [{ listenerUserId: user.id }, { channel: { userId: user.id } }] },
      orderBy: { createdAt: 'asc' },
      select: {
        enabled: true,
        position: true,
        configJson: true,
        createdAt: true,
        widget: { select: { slug: true, name: true } },
      },
    }),
    prisma.session.findMany({
      where: { userId: user.id },
      orderBy: { createdAt: 'asc' },
      select: { deviceLabel: true, createdAt: true, expiresAt: true },
    }),
    prisma.apiToken.findMany({
      where: { userId: user.id },
      orderBy: { createdAt: 'asc' },
      select: {
        name: true,
        tokenPrefix: true,
        scopes: true,
        lastUsedAt: true,
        expiresAt: true,
        revokedAt: true,
        createdAt: true,
      },
    }),
    prisma.soundShare.findMany({
      where: { sound: { channel: { userId: user.id } } },
      orderBy: { createdAt: 'asc' },
      select: {
        granteeUsername: true,
        permission: true,
        expiresAt: true,
        createdAt: true,
        sound: { select: { id: true, title: true } },
      },
    }),
    prisma.soundShare.findMany({
      where: { granteeUsername: user.username },
      orderBy: { createdAt: 'asc' },
      select: {
        permission: true,
        expiresAt: true,
        createdAt: true,
        sound: {
          select: {
            id: true,
            title: true,
            channel: { select: { user: { select: { username: true } } } },
          },
        },
      },
    }),
    prisma.broadcastGreenRoomInvite.findMany({
      where: { userId: user.id },
      orderBy: { invitedAt: 'asc' },
      select: {
        source: true,
        invitedAt: true,
        joinedAt: true,
        broadcast: { select: { channel: { select: { slug: true } } } },
      },
    }),
    prisma.emailChange.findMany({
      where: { userId: user.id },
      orderBy: { createdAt: 'asc' },
      select: { newEmail: true, createdAt: true, expiresAt: true, usedAt: true },
    }),
    prisma.discussionPost.findMany({
      where: { authorId: user.id },
      orderBy: { createdAt: 'asc' },
      select: { body: true, createdAt: true, topic: { select: { id: true, title: true } } },
    }),
    prisma.discussionParticipant.findMany({
      where: { userId: user.id },
      orderBy: { joinedAt: 'asc' },
      select: { joinedAt: true, mutedAt: true, topic: { select: { id: true, title: true } } },
    }),
  ])

  return {
    sounds,
    collections,
    posts,
    events,
    comments,
    likes,
    reposts,
    following,
    collectionSubscriptions,
    messagesSent,
    purchases,
    newsletterSubscriptions,
    supportRequests,
    blockedAccounts,
    listening,
    chatMessages,
    trackReactions,
    featureRequests,
    featureRequestComments,
    featureRequestVotes,
    motionComments,
    motionSeconds,
    motionVotes,
    correctionRequests,
    supportReplies,
    radioStations,
    themes,
    embeds,
    downloads,
    jams,
    venues,
    venueShows,
    restrictions,
    radioSubmissions,
    stationSuggestions,
    fanTiers,
    storeItems,
    notifications,
    grants: grants.map((grant) => ({ ...grant, amountCents: Number(grant.amountCents) })),
    fanSubscriptionPayouts,
    addonsPublished,
    addonInstalls,
    devices,
    apiTokens,
    sharesGiven,
    sharesReceived,
    greenRoomInvites,
    emailChanges,
    discussionPosts,
    discussionFollows,
  }
}
